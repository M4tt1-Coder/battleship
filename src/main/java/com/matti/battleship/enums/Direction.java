package com.matti.battleship.enums;

/**
 * Represents a direction ship can point to in 2-dimensional field.
 *
 * @author m4tt1
 */
public enum Direction {
  /** Ship pointing to the top of the field. */
  UP,
  /** Ship pointing to the bottom of the field. */
  DOWN,
  /** Ship pointing to the left of the field. */
  LEFT,
  /** Ship pointing to the right of the field. */
  RIGHT,
}
